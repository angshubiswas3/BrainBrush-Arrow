export function getHandcraftedLevel(levelIndex) {
  const all = ALL_HANDCRAFTED_LEVELS;
  const idx = typeof levelIndex === 'number' ? Math.floor(levelIndex) : 0;
  if (idx >= 0 && idx < all.length) {
    return all[idx];
  }
  const wrapped = Math.abs(idx) % all.length;
  return all[wrapped];
}
